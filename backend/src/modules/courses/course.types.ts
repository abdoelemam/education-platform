import type { Document, Types } from 'mongoose';

/**
 * Course lifecycle.
 *
 * The Course Builder creates `draft` courses. The Teacher Workflow owns the
 * review transitions (`draft`/`rejected` → `pending_review` → `approved` or
 * `rejected`). Publishing (`approved` → `published`) and archiving are later
 * phases and are not reachable yet.
 */
export const COURSE_STATUSES = [
  'draft',
  'pending_review',
  'approved',
  'rejected',
  'published',
  'archived',
] as const;
export type CourseStatus = (typeof COURSE_STATUSES)[number];

/**
 * Supported lesson types.
 *
 * `quiz` is part of the domain model but its content depends on the Quiz System
 * (Phase 10), so quiz lessons cannot be created yet.
 */
export const LESSON_TYPES = ['video', 'text', 'document', 'quiz'] as const;
export type LessonType = (typeof LESSON_TYPES)[number];

/**
 * Core Course entity. A course is the ownership boundary for its content.
 */
export interface ICourse {
  ownerId: Types.ObjectId;
  title: string;
  /** URL-safe, unique identifier generated by the server. */
  slug: string;
  description?: string;
  status: CourseStatus;
  /** Set whenever the owner submits the current version for review. */
  submittedAt?: Date;
  /** Set by the admin decision that reviewed the current submission. */
  reviewedAt?: Date;
  reviewedBy?: Types.ObjectId;
  /** Present only while the course is rejected; cleared on resubmission. */
  rejectionReason?: string;
  /**
   * Internal content-edit lease. A request that changes course content claims
   * this boolean before writing and releases it afterwards. Submission needs an
   * unlocked course, so a write that started just before submission cannot land
   * after the review snapshot is taken. Never accepted from clients and never
   * serialized in API responses.
   */
  editLocked: boolean;
  /** When the current edit lease was claimed; used to recover abandoned locks. */
  editLockedAt?: Date;
  /** Opaque token identifying the current lease holder. */
  editLockToken?: string;
  createdAt: Date;
  updatedAt: Date;
}

export interface CourseDocument extends ICourse, Document<Types.ObjectId> {
  _id: Types.ObjectId;
}

/**
 * A section always belongs to exactly one course and owns an ordered list of
 * lessons. Sections are stored in their own collection so ordering and
 * deletion stay simple as courses grow.
 */
export interface ISection {
  courseId: Types.ObjectId;
  title: string;
  description?: string;
  /** 1-based position within the course. Sparse values are allowed. */
  order: number;
  createdAt: Date;
  updatedAt: Date;
}

export interface SectionDocument extends ISection, Document<Types.ObjectId> {
  _id: Types.ObjectId;
}

/**
 * A lesson belongs to exactly one section (and, denormalized, one course).
 *
 * Type-specific payloads:
 * - `video`: `videoId` references an existing Video owned by the course owner.
 * - `text`: `content` holds the lesson body.
 * - `document`: `documentUrl` references an externally hosted document.
 *
 * Only fields relevant to a lesson's type are populated; switching type clears
 * the others so stale payloads cannot linger.
 */
export interface ILesson {
  courseId: Types.ObjectId;
  sectionId: Types.ObjectId;
  title: string;
  description?: string;
  type: LessonType;
  /** 1-based position within the section. Sparse values are allowed. */
  order: number;
  videoId?: Types.ObjectId;
  content?: string;
  documentUrl?: string;
  documentName?: string;
  createdAt: Date;
  updatedAt: Date;
}

export interface LessonDocument extends ILesson, Document<Types.ObjectId> {
  _id: Types.ObjectId;
}

/**
 * Sanitized lesson representation safe for API responses.
 */
export interface PublicLesson {
  id: string;
  title: string;
  description?: string;
  type: LessonType;
  order: number;
  videoId?: string;
  content?: string;
  documentUrl?: string;
  documentName?: string;
  createdAt: string;
  updatedAt: string;
}

/**
 * Sanitized section representation including its ordered lessons.
 */
export interface PublicSection {
  id: string;
  title: string;
  description?: string;
  order: number;
  lessons: PublicLesson[];
  createdAt: string;
  updatedAt: string;
}

/**
 * Audience-neutral course metadata.
 *
 * This is the mapper used for any future public/catalog response. It must not
 * contain review internals (`submittedAt`, `reviewedAt`, `reviewedBy`,
 * `rejectionReason`) or edit-lock fields.
 */
export interface PublicCourse {
  id: string;
  ownerId: string;
  title: string;
  slug: string;
  description?: string;
  status: CourseStatus;
  createdAt: string;
  updatedAt: string;
}

/**
 * Authorized course-management representation.
 *
 * Review metadata is part of the teacher/admin workflow and is only returned by
 * owner or admin endpoints. It is never accepted as input.
 */
export interface ManagedCourse extends PublicCourse {
  /** ISO timestamp of the current review submission, when one exists. */
  submittedAt?: string;
  /** ISO timestamp of the admin review decision, when one exists. */
  reviewedAt?: string;
  /** Admin user id that made the current review decision. */
  reviewedBy?: string;
  /** Reason supplied by the admin for the current rejection. */
  rejectionReason?: string;
}

/**
 * Full course representation used by the Course Builder: metadata plus the
 * ordered section/lesson structure.
 */
export interface CourseDetail extends ManagedCourse {
  sections: PublicSection[];
}
